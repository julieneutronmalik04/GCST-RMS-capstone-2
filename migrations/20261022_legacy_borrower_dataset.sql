-- Unknown contacts use a reserved .invalid address and an empty phone number.
-- Existing transaction names and department snapshots are preserved.

CREATE TABLE IF NOT EXISTS legacy_borrower_mappings (
  borrowed_id INT PRIMARY KEY,
  student_faculty_id VARCHAR(50) COLLATE utf8mb4_general_ci NOT NULL,
  original_name VARCHAR(201) NOT NULL,
  original_department VARCHAR(150) NOT NULL,
  migrated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_legacy_loan FOREIGN KEY (borrowed_id) REFERENCES borrowed(id) ON DELETE RESTRICT,
  CONSTRAINT fk_legacy_borrower FOREIGN KEY (student_faculty_id) REFERENCES borrowers(student_faculty_id) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

